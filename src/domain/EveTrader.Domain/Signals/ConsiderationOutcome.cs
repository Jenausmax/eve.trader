namespace EveTrader.Domain.Signals;

/// <summary>
/// Исход рассмотрения пары правилом. Три исхода, и они не сводятся к двум.
///
/// «Данных не хватило» записывается отдельно от «условия не выполнены», потому что без
/// этого оценка качества считает знаменатель неверно: пары, по которым мы молчали из-за
/// пробела, попали бы в «правило не советовало» и завысили бы его избирательность.
/// </summary>
public enum ConsiderationOutcome
{
    /// <summary>Условия выполнены — сигнал.</summary>
    Signal = 0,

    /// <summary>Данных хватило, условия не выполнены: знаем и не советуем.</summary>
    ConditionsNotMet = 1,

    /// <summary>Данных не хватило: не знаем.</summary>
    InsufficientData = 2,
}
