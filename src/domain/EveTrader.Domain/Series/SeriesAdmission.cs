namespace EveTrader.Domain.Series;

/// <summary>Что делать с точкой ряда по итогам разбора покрытия её окна.</summary>
public enum SeriesAdmission
{
    /// <summary>Окно покрыто полными наблюдениями — точка считается и годна для обучения.</summary>
    Admitted = 0,

    /// <summary>
    /// Окно покрыто, но содержит частичное наблюдение — точка считается и помечается
    /// неполной. Часть стакана на этот момент не была получена: величина занижена на
    /// неизвестную долю, и это ограничение точности, а не другая величина.
    /// </summary>
    AdmittedIncomplete = 1,

    /// <summary>
    /// В окне есть интервал, который не наблюдался, — точка не порождается вовсе.
    /// Посчитанная по половине окна величина не является неточной: она другая, и в
    /// обучении неотличима от настоящей.
    /// </summary>
    Refused = 2,
}
