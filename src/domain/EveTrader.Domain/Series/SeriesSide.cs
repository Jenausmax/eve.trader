namespace EveTrader.Domain.Series;

/// <summary>
/// Сторона стакана, к которой относится точка ряда.
///
/// Не <see langword="bool" />, как у ордера: у ордера сторона есть всегда, а признак
/// бывает и двусторонним — доля исчезновений с исполнением считается по обеим сторонам
/// сразу, и выдавать её за покупку или продажу было бы неправдой.
/// </summary>
public enum SeriesSide
{
    Buy = 0,
    Sell = 1,
    Both = 2,
}
