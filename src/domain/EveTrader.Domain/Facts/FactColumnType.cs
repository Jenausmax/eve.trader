namespace EveTrader.Domain.Facts;

/// <summary>Тип колонки набора. Набор типов узкий намеренно — расширяется по мере надобности.</summary>
public enum FactColumnType
{
    Int64 = 0,
    Double = 1,
    String = 2,

    /// <summary>
    /// Целое, которого может не быть. Нужно там, где отсутствие значения — само по себе
    /// утверждение: глубина и число ордеров у отсутствующей стороны стакана не записаны,
    /// а не равны нулю.
    /// </summary>
    NullableInt64 = 3,
}
