namespace EveTrader.Domain.Facts;

/// <summary>
/// Вид времени события. Различие обязано быть явным: источник сообщает точный момент
/// только там, где он его знает, а выдать интервал за момент — соврать модели о том,
/// что известно.
/// </summary>
public enum EventTimeKind
{
    /// <summary>Точный момент, сообщённый источником.</summary>
    Instant = 0,

    /// <summary>Интервал между наблюдениями: точнее источник не сообщает.</summary>
    Interval = 1,
}
