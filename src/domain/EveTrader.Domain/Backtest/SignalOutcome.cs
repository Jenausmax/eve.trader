namespace EveTrader.Domain.Backtest;

/// <summary>Чем кончился сигнал на горизонте оценки.</summary>
public enum SignalOutcome
{
    /// <summary>Круг замкнулся: на горизонте наблюдались исполнения по обе стороны по ценам сигнала.</summary>
    Success = 0,

    /// <summary>Горизонт наблюдался целиком, а круг не замкнулся: ордера пришлось бы снять.</summary>
    Failure = 1,

    /// <summary>
    /// Внутри горизонта был ненаблюдавшийся интервал — исход подтвердить нечем. Ни в успех,
    /// ни в неудачу не засчитывается.
    /// </summary>
    Unknown = 2,
}
