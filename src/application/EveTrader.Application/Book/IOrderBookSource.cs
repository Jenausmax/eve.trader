using EveTrader.Domain.Facts;

namespace EveTrader.Application.Book;

/// <summary>
/// Единый вход наблюдений стакана. Его реализуют архив снимков и живой сбор с ESI, и
/// это не удобство, а проверка: если стадии после приёма где-то различают источник,
/// различие вылезет здесь.
///
/// Источник обязан объявить форму наблюдения — шаг между наблюдениями и границы
/// интервала сбора. Шаг доезжает до записи покрытия и там становится единственным, чем
/// потребитель имеет право различать происхождение факта.
/// </summary>
public interface IOrderBookSource
{
    /// <summary>Имя источника; попадает в запись покрытия.</summary>
    string Name { get; }

    /// <summary>
    /// Объявленный шаг между наблюдениями. Свойство данных, а не настройка опроса:
    /// архив снимает рынок раз в тридцать минут, и никакая наша настройка этого не
    /// изменит.
    /// </summary>
    TimeSpan Step { get; }

    /// <summary>
    /// Моменты снимков, которые источник публикует в интервале, по возрастанию. Нужны
    /// отдельно от самих снимков: по ним выбирается точка продолжения после обрыва, и
    /// выбирать её, уже скачав окно, было бы поздно.
    /// </summary>
    Task<IReadOnlyList<DateTimeOffset>> AvailableSnapshotsAsync(
        TimeRange within,
        CancellationToken cancellationToken);

    /// <summary>
    /// Имя снимка у источника — устойчивое между прогонами и уникальное. Объявляется
    /// отдельно от загрузки, потому что по нему узнаётся, какие снимки уже сворачивались:
    /// выяснять это, уже скачав окно, было бы поздно.
    /// </summary>
    string KeyFor(DateTimeOffset snapshotAt);

    /// <summary>
    /// Названные снимки, строго по возрастанию времени. Порядок — требование, а не
    /// удобство: свёртка держит состояние, и снимок, пришедший раньше предыдущего, дал
    /// бы выдуманные события, а не более быструю загрузку.
    /// </summary>
    IAsyncEnumerable<OrderBookObservation> ObserveAsync(
        IReadOnlyList<DateTimeOffset> snapshots,
        OrderBookScope scope,
        CancellationToken cancellationToken);
}
