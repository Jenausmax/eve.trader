namespace EveTrader.Application.Intake;

/// <summary>
/// Единый вход наблюдений. Его реализуют живой ESI, импорт внешнего архива и реплей
/// собственного озера.
///
/// Один контракт, а не три похожих: ветвление по типу источника допускается ровно в
/// одном месте — при создании реализации, — и дальше по конвейеру не проникает. Реплей
/// поэтому и доказывает единство входа: если бы для него пришлось изменить домен или
/// свёртку, доказательство провалилось бы, даже совпади результаты.
/// </summary>
public interface IObservationSource
{
    /// <summary>Имя источника; попадает в запись покрытия.</summary>
    string Name { get; }

    /// <summary>
    /// Наблюдения по возрастанию времени в пределах региона. Порядок — требование:
    /// свёртка держит состояние, и наблюдение, пришедшее раньше предыдущего, дало бы
    /// выдуманные события.
    /// </summary>
    IAsyncEnumerable<RegionObservation> ObserveAsync(CancellationToken cancellationToken);
}
